public class ErrorResponse {
  /* ********************************************************************************************
   * CLASS VARIABLES
   *********************************************************************************************/
  private final String message;

  /* ********************************************************************************************
   * CONSTRUCTOR METHODS
   *********************************************************************************************/

  /* ********************************************************************************************
   * PRIVATE METHODS
   *********************************************************************************************/

  /* ********************************************************************************************
   * PROTECTED METHODS
   *********************************************************************************************/

  /* ********************************************************************************************
   * PUBLIC METHODS
   *********************************************************************************************/

  public ErrorResponse(String message) {
    this.message = message;
  }

  public String getMessage() {
    return message;
  }

  @Override
  public String toString() {
    return "ErrorResponse{" +
        "message='" + message + '\'' +
        '}';
  }
}
