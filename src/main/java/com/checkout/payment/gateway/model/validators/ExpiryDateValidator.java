import com.checkout.payment.gateway.model.PostPaymentRequest;
import jakarta.validation.ConstraintValidator;
import jakarta.validation.ConstraintValidatorContext;

import java.time.YearMonth;
// ------------------------------------------------------------------------------------------------
// ================================================================================================
// CLASS DEFINITION
// ================================================================================================
// ------------------------------------------------------------------------------------------------


/**
 * ExpiryDateValidator.
 *
 * <p></p>
 */
public class ExpiryDateValidator implements ConstraintValidator<ValidExpiryDate, PostPaymentRequest> {
  /* ********************************************************************************************
   * CLASS VARIABLES
   *********************************************************************************************/

  /* ********************************************************************************************
   * CONSTRUCTOR METHODS
   *********************************************************************************************/

  /* ********************************************************************************************
   * PRIVATE METHODS
   *********************************************************************************************/

  /* ********************************************************************************************
   * PROTECTED METHODS
   *********************************************************************************************/

  /* ********************************************************************************************
   * PUBLIC METHODS
   *********************************************************************************************/
  @Override
  public boolean isValid(PostPaymentRequest req, ConstraintValidatorContext context) {
    try {
      YearMonth now = YearMonth.now();
      YearMonth expiry = YearMonth.of(req.getExpiryYear(), req.getExpiryMonth());
      return expiry.isAfter(now);
    } catch (java.time.DateTimeException e) {
      return false;
    }
  }
}
